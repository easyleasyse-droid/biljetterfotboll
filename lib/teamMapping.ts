// Hjälpfunktion för att hämta din nyckel
export function getTeamKey(apiTeamName: string): string {
  if (teamMapping[apiTeamName]) {
    return teamMapping[apiTeamName];
  }

  // Fallback om något okänt lag dyker upp i framtiden
  return apiTeamName
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
}